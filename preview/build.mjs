// Builds preview/data.json from the real layout, the real theme files and the
// real droid spec in mods/droids/. The preview is generated, never redrawn by
// hand: if the layout or a theme changes, re-run `node preview/build.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { KINDS, STATES, W, H, build, cradle, palette } from "../mods/droids/droids.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const json = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));

const flat = (f) => ({ ...f, ...(f.colors ?? {}) });
const dark = flat(json("themes/droids-dark.json"));
const light = flat(json("themes/droids-light.json"));

const droids = { cradle: {} };
for (const kind of [...KINDS.map((k) => k.id)]) {
  droids[kind] = {};
  for (const state of STATES) {
    droids[kind][state] = {
      dark: build(kind, state, palette(dark, true)),
      light: build(kind, state, palette(light, false)),
    };
  }
}
droids.cradle = {
  dark: { w: W, h: H, children: cradle(palette(dark, true)) },
  light: { w: W, h: H, children: cradle(palette(light, false)) },
};

const data = {
  layout: json("layouts/droids.json"),
  themes: { dark, light },
  droids,
  meta: {
    kinds: KINDS.map(({ id, name, droid, match }) => ({ id, name, droid, match })),
    states: STATES,
    box: { w: W, h: H },
  },
};

writeFileSync(join(here, "data.js"), `// generated by preview/build.mjs — do not edit\nwindow.HERDR_DATA = ${JSON.stringify(data)};\n`);
const parts = Object.values(droids).reduce((n, v) => n + (v.dark ? 1 : Object.values(v).reduce((m, s) => m + Object.keys(s).length, 0)), 0);
console.log(`preview/data.js: ${KINDS.length} kinds x ${STATES.length} states x 2 appearances, box ${W}x${H}`);
